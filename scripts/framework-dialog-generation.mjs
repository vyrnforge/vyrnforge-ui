function angularSource() {
  return `${GENERATED_HEADER}
import {
  Directive,
  ElementRef,
  EventEmitter,
  Input,
  OnDestroy,
  Output,
} from "@angular/core";
import type { VyrnForgeElementForTagName } from "@vyrnforge/ui-elements";

export type VfDialogElement = VyrnForgeElementForTagName<"vf-dialog">;

export interface GeneratedDialogOpenChangeDetail {
  open: boolean;
  previousOpen?: boolean;
  reason: string;
}

export interface GeneratedDialogDismissDetail {
  id?: string;
  reason: string;
}

@Directive({
  selector: "vf-dialog[vfGeneratedDialog]",
  standalone: true,
  exportAs: "vfDialog",
})
export class VfDialog implements OnDestroy {
  @Output("openChange")
  readonly openChange = new EventEmitter<boolean>();

  @Output("dismiss")
  readonly dismiss = new EventEmitter<GeneratedDialogDismissDetail>();

  private hasOpenInput = false;

  private readonly handleOpenChange = (event: Event) => {
    const detail = (event as CustomEvent<GeneratedDialogOpenChangeDetail>).detail;
    this.openChange.emit(detail.open);
  };

  private readonly handleDismiss = (event: Event) => {
    this.dismiss.emit((event as CustomEvent<GeneratedDialogDismissDetail>).detail);
  };

  constructor(private readonly element: ElementRef<VfDialogElement>) {
    this.element.nativeElement.dataset["vfGeneratedDialog"] = "angular";
    this.element.nativeElement.addEventListener("vf-open-change", this.handleOpenChange);
    this.element.nativeElement.addEventListener("vf-dismiss", this.handleDismiss);
  }

  @Input("open")
  set openInput(value: boolean | undefined) {
    if (value === undefined) return;
    this.hasOpenInput = true;
    if (this.element.nativeElement.open !== value) this.element.nativeElement.open = value;
  }

  @Input("defaultOpen")
  set defaultOpenInput(value: boolean | undefined) {
    if (value !== undefined && !this.hasOpenInput && this.element.nativeElement.open !== value) {
      this.element.nativeElement.open = value;
    }
  }

  @Input("modal")
  set modalInput(value: boolean | undefined) {
    if (value !== undefined && this.element.nativeElement.modal !== value) {
      this.element.nativeElement.modal = value;
    }
  }

  @Input("closeOnEscape")
  set closeOnEscapeInput(value: boolean | undefined) {
    if (value !== undefined && this.element.nativeElement.closeOnEscape !== value) {
      this.element.nativeElement.closeOnEscape = value;
    }
  }

  @Input("closeOnOutsidePointer")
  set closeOnOutsidePointerInput(value: boolean | undefined) {
    if (value !== undefined && this.element.nativeElement.closeOnOutsidePointer !== value) {
      this.element.nativeElement.closeOnOutsidePointer = value;
    }
  }

  @Input("description")
  set descriptionInput(value: string | undefined) {
    if (value !== undefined && this.element.nativeElement.description !== value) {
      this.element.nativeElement.description = value;
    }
  }

  @Input("disabled")
  set disabledInput(value: boolean | undefined) {
    if (value !== undefined && this.element.nativeElement.disabled !== value) {
      this.element.nativeElement.disabled = value;
    }
  }

  @Input("size")
  set sizeInput(value: "sm" | "md" | "lg" | "xl" | undefined) {
    if (value !== undefined && this.element.nativeElement.size !== value) {
      this.element.nativeElement.size = value;
    }
  }

  @Input("title")
  set titleInput(value: string | undefined) {
    if (value !== undefined && this.element.nativeElement.title !== value) {
      this.element.nativeElement.title = value;
    }
  }

  show(): void {
    this.element.nativeElement.show();
  }

  close(): void {
    this.element.nativeElement.close();
  }

  focus(): void {
    this.element.nativeElement.focus();
  }

  ngOnDestroy(): void {
    this.element.nativeElement.removeEventListener("vf-open-change", this.handleOpenChange);
    this.element.nativeElement.removeEventListener("vf-dismiss", this.handleDismiss);
  }
}
`;
}

function vueSource() {
  return `${GENERATED_HEADER}
import {
  defineComponent,
  h,
  onBeforeUnmount,
  onMounted,
  ref,
  watchEffect,
} from "vue";
import type { PropType } from "vue";
import type { VyrnForgeElementForTagName } from "@vyrnforge/ui-elements";

export type VfDialogElement = VyrnForgeElementForTagName<"vf-dialog">;

export interface GeneratedDialogOpenChangeDetail {
  open: boolean;
  previousOpen?: boolean;
  reason: string;
}

export interface GeneratedDialogDismissDetail {
  id?: string;
  reason: string;
}

export const VfDialog = defineComponent({
  name: "VfDialog",
  inheritAttrs: false,
  props: {
    id: { type: String, default: undefined },
    open: { type: Boolean as PropType<boolean | undefined>, default: undefined },
    defaultOpen: { type: Boolean, default: false },
    modal: { type: Boolean, default: true },
    closeOnEscape: { type: Boolean, default: true },
    closeOnOutsidePointer: { type: Boolean, default: true },
    description: { type: String, default: undefined },
    disabled: { type: Boolean, default: false },
    size: { type: String as PropType<"sm" | "md" | "lg" | "xl">, default: "md" },
    title: { type: String, default: undefined },
  },
  emits: {
    "update:open": (_value: boolean) => true,
    dismiss: (_detail: GeneratedDialogDismissDetail) => true,
  },
  setup(props, { attrs, emit, expose, slots }) {
    const elementRef = ref<VfDialogElement | null>(null);
    let initialized = false;

    watchEffect(() => {
      const element = elementRef.value;
      if (!element) return;
      if (!initialized) {
        if (props.open === undefined && element.open !== props.defaultOpen) {
          element.open = props.defaultOpen;
        }
        initialized = true;
      }
      if (props.open !== undefined && element.open !== props.open) element.open = props.open;
      if (element.modal !== props.modal) element.modal = props.modal;
      if (element.closeOnEscape !== props.closeOnEscape) element.closeOnEscape = props.closeOnEscape;
      if (element.closeOnOutsidePointer !== props.closeOnOutsidePointer) {
        element.closeOnOutsidePointer = props.closeOnOutsidePointer;
      }
      if (props.description !== undefined && element.description !== props.description) {
        element.description = props.description;
      }
      if (element.disabled !== props.disabled) element.disabled = props.disabled;
      if (element.size !== props.size) element.size = props.size;
      if (props.title !== undefined && element.title !== props.title) element.title = props.title;
    });

    const handleOpenChange = (event: Event) => {
      const detail = (event as CustomEvent<GeneratedDialogOpenChangeDetail>).detail;
      emit("update:open", detail.open);
    };
    const handleDismiss = (event: Event) => {
      emit("dismiss", (event as CustomEvent<GeneratedDialogDismissDetail>).detail);
    };

    onMounted(() => {
      elementRef.value?.addEventListener("vf-open-change", handleOpenChange);
      elementRef.value?.addEventListener("vf-dismiss", handleDismiss);
    });
    onBeforeUnmount(() => {
      elementRef.value?.removeEventListener("vf-open-change", handleOpenChange);
      elementRef.value?.removeEventListener("vf-dismiss", handleDismiss);
    });

    expose({
      element: elementRef,
      show: () => elementRef.value?.show(),
      close: () => elementRef.value?.close(),
      focus: () => elementRef.value?.focus(),
    });

    return () =>
      h(
        "vf-dialog",
        {
          ...attrs,
          id: props.id,
          ref: elementRef,
          "data-vf-generated-dialog": "vue",
        },
        [
          slots.trigger ? h("span", { slot: "trigger" }, slots.trigger()) : null,
          slots.header ? h("div", { slot: "header" }, slots.header()) : null,
          h("div", { slot: "content" }, slots.content?.() ?? []),
          slots.actions ? h("div", { slot: "actions" }, slots.actions()) : null,
          slots.footer ? h("div", { slot: "footer" }, slots.footer()) : null,
        ],
      );
  },
});

export default VfDialog;
`;
}

