import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
);
const outputArgumentIndex = process.argv.indexOf("--output");
const output =
  outputArgumentIndex >= 0 && process.argv[outputArgumentIndex + 1]
    ? process.argv[outputArgumentIndex + 1]
    : "docs/governance/repository-inventory.md";

function read(relativePath) {
  return readFileSync(path.join(root, relativePath), "utf8");
}

function json(relativePath) {
  return JSON.parse(read(relativePath));
}

function walk(directory, match = () => true) {
  const absolute = path.join(root, directory);
  if (!existsSync(absolute)) return [];

  return readdirSync(absolute, { withFileTypes: true })
    .flatMap((entry) => {
      if ([".git", "dist", "node_modules"].includes(entry.name)) return [];

      const relativePath = path.posix.join(directory, entry.name);
      return entry.isDirectory()
        ? walk(relativePath, match)
        : match(relativePath)
          ? [relativePath]
          : [];
    })
    .sort((left, right) => left.localeCompare(right));
}

function childDirectories(directory) {
  const absolute = path.join(root, directory);
  if (!existsSync(absolute)) return [];

  return readdirSync(absolute, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function codeList(values, fallback = "None") {
  return values.length
    ? values.map((value) => `\`${value}\``).join(", ")
    : fallback;
}

const rootPackage = json("package.json");
const packageRecords = childDirectories("packages")
  .filter((directory) =>
    existsSync(path.join(root, "packages", directory, "package.json")),
  )
  .map((directory) => ({
    directory,
    manifest: json(`packages/${directory}/package.json`),
  }));
const applications = [
  ...childDirectories("apps").map((directory) => `apps/${directory}`),
  ...childDirectories("examples").map((directory) => `examples/${directory}`),
];
const activeDocs = walk(
  "docs",
  (file) => file.endsWith(".md") && !file.includes("/archive/"),
);
const archivedDocs = walk("docs/archive", (file) => file.endsWith(".md"));
const workflows = walk(
  ".github/workflows",
  (file) => file.endsWith(".yml") || file.endsWith(".yaml"),
);

const outputLines = [
  "# Repository Inventory",
  "",
  "Generated by `npm run inventory:repository`. This file is a compact navigation and measurement view. It does not replace canonical architecture, API, package, metadata, release, or testing sources.",
  "",
  "## Repository shape",
  "",
  table(
    ["Area", "Current inventory"],
    [
      ["Workspace globs", codeList(rootPackage.workspaces ?? [])],
      ["Packages", codeList(packageRecords.map(({ manifest }) => manifest.name))],
      ["Applications and examples", codeList(applications)],
      ["Active Markdown docs", String(activeDocs.length)],
      ["Archived Markdown docs", String(archivedDocs.length)],
      ["Root npm scripts", String(Object.keys(rootPackage.scripts ?? {}).length)],
      ["GitHub workflow files", String(workflows.length)],
    ],
  ),
  "",
  "## Package navigation",
  "",
  table(
    ["Package", "Source", "Canonical package documentation"],
    packageRecords.map(({ directory, manifest }) => [
      `\`${manifest.name}\``,
      `\`packages/${directory}/\``,
      `\`docs/packages/${directory}.md\``,
    ]),
  ),
  "",
  "## Canonical sources",
  "",
  table(
    ["Concern", "Canonical source"],
    [
      ["Documentation entrypoint", "`docs/README.md`"],
      ["Project identity", "`docs/governance/01-project-source-of-truth.md`"],
      ["Package boundaries", "`docs/architecture/01-package-boundaries.md`"],
      ["Public API", "`docs/api/README.md` and package API documents"],
      ["Component catalog and maturity", "`docs/metadata/components.json`"],
      ["Package metadata", "`docs/metadata/packages.json`"],
      ["Release groups", "`docs/metadata/release-groups.json`"],
      ["Current roadmap", "`docs/roadmap/00-master-roadmap.md`"],
      ["CI/CD architecture", "`docs/engineering/ci-cd-architecture.md`"],
      ["Documentation system", "`docs/engineering/documentation-system.md`"],
      ["Docs application route registry", "`apps/docs/src/docsRegistry.ts`"],
      ["AI context", "`AGENTS.md` and `.ai/`"],
    ],
  ),
  "",
  "## Maintenance",
  "",
  "Regenerate this file after repository-shape changes:",
  "",
  "```bash",
  "npm run inventory:repository",
  "```",
  "",
  "Do not expand this generated inventory into another hand-maintained component catalog, public API reference, test report, roadmap, or technical-debt register. Update the canonical owner for those topics instead.",
  "",
];

writeFileSync(path.resolve(root, output), outputLines.join("\n"), "utf8");
console.log(`Repository inventory generated: ${path.resolve(root, output)}`);
