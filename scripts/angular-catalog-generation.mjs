import { loadCanonicalComponentContracts } from "./canonical-component-contracts.mjs";
import {
  findFrameworkExceptions,
  loadFrameworkExceptions,
} from "./framework-exceptions.mjs";
import { createFrameworkGenerationModel } from "./framework-generation.mjs";

export const ANGULAR_CATALOG_ARTIFACT_PATH =
  "packages/ui-angular/src/generated/catalog.generated.ts";
export const ANGULAR_CATALOG_TASK = "MFD-1204";
export const ANGULAR_CATALOG_EXPECTED_SIZE = 59;

const SPECIALIZED = new Map([
  ["button", { exportName: "VfButton", path: "./vf-button.generated.js" }],
  ["dialog", { exportName: "VfDialog", path: "./vf-dialog.generated.js" }],
  ["tabs", { exportName: "VfTabs", path: "./vf-tabs.generated.js" }],
  [
    "text-input",
    { exportName: "VfTextInput", path: "./vf-text-input.generated.js" },
  ],
]);
const SUPPORTED_STATUSES = new Set(["current", "target"]);
const GENERATED_HEADER = `/**
 * @generated by scripts/angular-catalog-generation.mjs
 * Source: docs/metadata/component-contracts.json
 * DO NOT EDIT. Regenerate with: npm run generate:framework-artifacts
 */`;

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function assert(condition, message) {
  if (!condition) throw new Error(`Angular catalog generation: ${message}`);
}

function identifier(value) {
  const normalized = value.replace(/[^a-zA-Z0-9_$]/gu, "_");
  return /^[a-zA-Z_$]/u.test(normalized) ? normalized : `_${normalized}`;
}

function directiveMarker(exportName) {
  assert(exportName.startsWith("Vf"), `${exportName}: expected Vf export prefix`);
  return `vfGenerated${exportName.slice(2)}`;
}

function exportAsName(exportName) {
  return `${exportName[0].toLowerCase()}${exportName.slice(1)}`;
}

function findActiveAngularException(registry, componentId) {
  const matches = findFrameworkExceptions(registry, {
    framework: "angular",
    scope: componentId,
  });
  assert(
    matches.length <= 1,
    `${componentId}: multiple active Angular exceptions are not allowed`,
  );
  return matches[0] ?? null;
}

function mappedEventField(record, event) {
  if (event.detail === "value") return "value";
  if (event.detail !== "mapped") return null;

  const modelProperty = record.model?.property;
  if (
    modelProperty &&
    event.detailFields.some((field) => field.name === modelProperty)
  ) {
    return modelProperty;
  }
  if (event.detailFields.length === 1) return event.detailFields[0].name;
  return null;
}

function normalizeGeneratedComponent(record, nativeRecord) {
  assert(record.export, `${record.id}: Angular mapping requires an export`);
  assert(nativeRecord?.tag, `${record.id}: Native mapping requires a tag`);
  assert(
    record.package === "@vyrnforge/ui-angular",
    `${record.id}: unexpected Angular package ${String(record.package)}`,
  );
  assert(
    record.adapter.canonicalRenderer === "@vyrnforge/ui-elements",
    `${record.id}: Angular facade must delegate rendering to ui-elements`,
  );

  const specialized = SPECIALIZED.get(record.id) ?? null;
  if (specialized) {
    assert(
      specialized.exportName === record.export,
      `${record.id}: specialized export drifted from canonical mapping`,
    );
  }

  const outputAliases = new Set(record.events.map((event) => event.public));
  const properties = record.properties.filter(
    (property) => property.readOnly !== true && property.binding !== "readonly",
  );
  if (!specialized) {
    for (const property of properties) {
      assert(
        !outputAliases.has(property.public),
        `${record.id}: input/output alias ${property.public} requires specialization or an approved exception`,
      );
    }
    for (const event of record.events) {
      assert(
        event.mode === "output",
        `${record.id}: Angular event ${event.canonical} must use output mode`,
      );
      if (event.detail === "mapped") {
        assert(
          mappedEventField(record, event),
          `${record.id}: mapped output ${event.public} needs a deterministic canonical field or specialization`,
        );
      }
      if (event.detail === "value") {
        assert(
          event.detailFields.some((field) => field.name === "value"),
          `${record.id}: value output ${event.public} is missing canonical detail.value`,
        );
      }
    }
  }

  return Object.freeze({
    kind: specialized ? "specialized" : "generated",
    id: record.id,
    exportName: record.export,
    tag: nativeRecord.tag,
    selector: `${nativeRecord.tag}[${directiveMarker(record.export)}]`,
    exportAs: exportAsName(record.export),
    specialized,
    properties: Object.freeze(properties.map((property) => Object.freeze({ ...property }))),
    events: Object.freeze(record.events.map((event) => Object.freeze({ ...event }))),
    slots: Object.freeze(record.slots.map((slot) => Object.freeze({ ...slot }))),
    methods: Object.freeze(record.methods.map((method) => Object.freeze({ ...method }))),
  });
}

export function createAngularCatalogModel(generationModel, exceptionRegistry) {
  const angularById = new Map(
    generationModel.surfaces.angular.components.map((record) => [
      record.id,
      record,
    ]),
  );
  const nativeSupported = generationModel.surfaces.native.components
    .filter((record) => record.status === "current")
    .sort((left, right) => compareText(left.id, right.id));

  assert(
    nativeSupported.length === ANGULAR_CATALOG_EXPECTED_SIZE,
    `expected ${ANGULAR_CATALOG_EXPECTED_SIZE} supported non-grid contracts, received ${nativeSupported.length}`,
  );

  const components = [];
  const exceptions = [];
  for (const nativeRecord of nativeSupported) {
    const angularRecord = angularById.get(nativeRecord.id);
    assert(angularRecord, `${nativeRecord.id}: missing Angular generation record`);
    const exception = findActiveAngularException(exceptionRegistry, nativeRecord.id);

    if (angularRecord.status === "exception") {
      assert(
        exception,
        `${nativeRecord.id}: exception mapping requires an active framework exception record`,
      );
      exceptions.push(
        Object.freeze({
          kind: "exception",
          id: nativeRecord.id,
          exceptionId: exception.id,
          state: exception.state,
        }),
      );
      continue;
    }

    assert(
      SUPPORTED_STATUSES.has(angularRecord.status),
      `${nativeRecord.id}: unsupported Angular status ${angularRecord.status}; use generated/current/target or an approved exception`,
    );
    components.push(normalizeGeneratedComponent(angularRecord, nativeRecord));
  }

  assert(
    components.length + exceptions.length === ANGULAR_CATALOG_EXPECTED_SIZE,
    "every supported contract must be generated/specialized or covered by an active Angular exception",
  );
  assert(
    new Set(components.map((entry) => entry.exportName)).size === components.length,
    "duplicate Angular exports",
  );
  assert(
    new Set(components.map((entry) => entry.selector)).size === components.length,
    "duplicate Angular selectors",
  );

  return Object.freeze({
    components: Object.freeze(components),
    exceptions: Object.freeze(exceptions),
  });
}

function eventOutputType(event) {
  if (event.detail === "event") return "Event";
  const detailType = `VyrnForgeCanonicalEventDetailMap[\"${event.canonical}\"]`;
  if (event.detail === "detail") return detailType;
  const field = event.detail === "value" ? "value" : null;
  return field ? `${detailType}[\"${field}\"]` : detailType;
}

function eventOutputExpression(component, event) {
  if (event.detail === "event") return "event";
  const detail = `(event as CustomEvent<VyrnForgeCanonicalEventDetailMap[\"${event.canonical}\"]>).detail`;
  if (event.detail === "detail") return detail;
  const field = mappedEventField(component, event);
  assert(
    field,
    `${component.id}: ${event.public} has no deterministic mapped detail field`,
  );
  return `${detail}[\"${field}\"]`;
}

function inputSource(component, property) {
  const member = identifier(`${property.public}Input`);
  return `  @Input("${property.public}")\n  set ${member}(value: ${component.exportName}Element[\"${property.canonical}\"] | undefined) {\n    if (value !== undefined) {\n      this.element.nativeElement[\"${property.canonical}\"] = value;\n    }\n  }`;
}

function outputSource(component, event) {
  const member = identifier(`${event.public}Output`);
  const handler = identifier(`handle_${event.public}`);
  return {
    declaration: `  @Output("${event.public}")\n  readonly ${member} = new EventEmitter<${eventOutputType(event)}>();`,
    handler,
    handlerSource: `  private readonly ${handler} = (event: Event) => {\n    this.${member}.emit(${eventOutputExpression(component, event)});\n  };`,
    add: `    this.element.nativeElement.addEventListener(\n      "${event.canonical}",\n      this.${handler},\n    );`,
    remove: `    this.element.nativeElement.removeEventListener(\n      "${event.canonical}",\n      this.${handler},\n    );`,
  };
}

function methodSource(component, method) {
  const name = identifier(method.name);
  return `  ${name}(\n    ...args: Parameters<${component.exportName}Element[\"${method.name}\"]>\n  ): ReturnType<${component.exportName}Element[\"${method.name}\"]> {\n    return this.element.nativeElement[\"${method.name}\"](...args);\n  }`;
}

function slotSource(component) {
  const values = component.slots.map((slot) => `"${slot.public}"`).join(", ");
  return `export const ${component.exportName}SlotNames = Object.freeze([${values}] as const);\nexport type ${component.exportName}SlotName = (typeof ${component.exportName}SlotNames)[number];\n\nexport function compose${component.exportName}Slot(\n  element: HTMLElement,\n  slot: ${component.exportName}SlotName,\n): HTMLElement {\n  if (slot === "default") element.removeAttribute("slot");\n  else element.setAttribute("slot", slot);\n  return element;\n}`;
}

function genericDirectiveSource(component) {
  const outputs = component.events.map((event) => outputSource(component, event));
  const inputs = component.properties.map((property) => inputSource(component, property));
  const methods = component.methods.map((method) => methodSource(component, method));
  const marker = directiveMarker(component.exportName);

  const bodySections = [
    `  get nativeElement(): ${component.exportName}Element {\n    return this.element.nativeElement;\n  }`,
    ...inputs,
    ...outputs.map((output) => output.declaration),
    ...outputs.map((output) => output.handlerSource),
    `  constructor(private readonly element: ElementRef<${component.exportName}Element>) {\n    this.element.nativeElement.dataset[\"${marker}\"] = \"angular\";${
      outputs.length > 0 ? `\n${outputs.map((output) => output.add).join("\n")}` : ""
    }\n  }`,
    ...methods,
    `  ngOnDestroy(): void {${
      outputs.length > 0 ? `\n${outputs.map((output) => output.remove).join("\n")}` : ""
    }\n  }`,
  ];

  return `export type ${component.exportName}Element = VyrnForgeElementForTagName<\"${component.tag}\">;\n\n${slotSource(component)}\n\n@Directive({\n  selector: \"${component.selector}\",\n  standalone: true,\n  exportAs: \"${component.exportAs}\",\n})\nexport class ${component.exportName} implements OnDestroy {\n${bodySections.join("\n\n")}\n}`;
}

function specializedImports(components) {
  return components
    .filter((component) => component.specialized)
    .map(
      (component) =>
        `import { ${component.exportName} } from "${component.specialized.path}";`,
    )
    .join("\n");
}

function registrySource(components) {
  const lines = components.map((component) => `  ${component.exportName},`).join("\n");
  return `export const vyrnForgeAngularGeneratedDirectives = Object.freeze([\n${lines}\n]);`;
}

function metadataSource(components, exceptions) {
  const componentLines = components
    .map(
      (component) =>
        `  Object.freeze({ id: "${component.id}", tag: "${component.tag}", selector: "${component.selector}", directive: ${component.exportName}, slots: ${component.exportName}SlotNames }),`,
    )
    .join("\n");
  const exceptionLines = exceptions
    .map(
      (exception) =>
        `  Object.freeze({ id: "${exception.id}", exceptionId: "${exception.exceptionId}", state: "${exception.state}" }),`,
    )
    .join("\n");
  return `export const vyrnForgeAngularCatalog = Object.freeze([\n${componentLines}\n]);\n\nexport const vyrnForgeAngularCatalogExceptions = Object.freeze([\n${exceptionLines}\n]);`;
}

export function serializeAngularCatalog(model) {
  const generic = model.components
    .filter((component) => !component.specialized)
    .map(genericDirectiveSource)
    .join("\n\n");
  const specializedSlotHelpers = model.components
    .filter((component) => component.specialized)
    .map((component) => `${slotSource(component)}\n\nexport type ${component.exportName}Element = VyrnForgeElementForTagName<\"${component.tag}\">;`)
    .join("\n\n");

  return `${GENERATED_HEADER}\nimport {\n  Directive,\n  ElementRef,\n  EventEmitter,\n  Input,\n  OnDestroy,\n  Output,\n} from "@angular/core";\nimport type {\n  VyrnForgeCanonicalEventDetailMap,\n  VyrnForgeElementForTagName,\n} from "@vyrnforge/ui-elements";\n\n${specializedImports(model.components)}\n\n${specializedSlotHelpers}\n\n${generic}\n\n${registrySource(model.components)}\n\n${metadataSource(model.components, model.exceptions)}\n`;
}

export function buildAngularCatalogArtifact({ root } = {}) {
  const contracts = loadCanonicalComponentContracts({ root });
  const generationModel = createFrameworkGenerationModel(contracts);
  const exceptionRegistry = loadFrameworkExceptions({ root });
  const model = createAngularCatalogModel(generationModel, exceptionRegistry);
  return Object.freeze({
    path: ANGULAR_CATALOG_ARTIFACT_PATH,
    sourceRecords: Object.freeze([
      "component:*",
      "framework:angular:*",
      "framework:native:*",
      "framework-exception:angular:*",
    ]),
    content: serializeAngularCatalog(model),
    components: model.components,
    exceptions: model.exceptions,
  });
}
