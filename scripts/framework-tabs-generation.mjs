export const FRAMEWORK_TABS_COMPONENT_ID = "tabs";

export const FRAMEWORK_TABS_ARTIFACT_PATHS = Object.freeze({
  native: "tests/consumers/native-html/src/generated/vf-tabs.generated.ts",
  react: "tests/consumers/react/src/generated/Tabs.generated.tsx",
  angular: "tests/consumers/angular/src/app/generated/vf-tabs.generated.ts",
  vue: "tests/consumers/vue/src/generated/VfTabs.generated.ts",
});

const TASK_ID = "MFD-1114";
const CANONICAL_RENDERER = "@vyrnforge/ui-elements";
const REQUIRED_PROPERTIES = Object.freeze([
  "value",
  "activationMode",
  "items",
  "orientation",
  "disabledValues",
  "size",
  "variant",
]);
const REQUIRED_ACCESSIBILITY = Object.freeze([
  "tablist semantics",
  "roving focus",
  "aria-controls",
  "aria-selected",
  "manual/automatic activation",
]);

const GENERATED_HEADER = `/**
 * @generated by scripts/generate-framework-tabs-slice.mjs
 * Source: docs/metadata/component-contracts.json (component:tabs)
 * DO NOT EDIT. Regenerate with: npm run generate:framework-artifacts
 */`;

export class FrameworkTabsGenerationError extends Error {
  constructor(message) {
    super(message);
    this.name = "FrameworkTabsGenerationError";
  }
}

function assert(condition, message) {
  if (!condition) throw new FrameworkTabsGenerationError(message);
}

function findProperty(record, canonical) {
  return record.properties.find((property) => property.canonical === canonical);
}

function findEvent(record, canonical) {
  return record.events.find((event) => event.canonical === canonical);
}

function assertRecord(record, framework) {
  assert(record, `tabs: missing ${framework} generation record`);
  assert(
    record.id === FRAMEWORK_TABS_COMPONENT_ID,
    `${framework}: expected tabs record`,
  );
  assert(
    record.adapter.canonicalRenderer === CANONICAL_RENDERER,
    `${framework}: Tabs must keep ${CANONICAL_RENDERER} as canonical renderer`,
  );
  if (framework === "native") {
    assert(record.tag === "vf-tabs", "native: Tabs must target vf-tabs");
  }
  for (const property of REQUIRED_PROPERTIES) {
    assert(
      findProperty(record, property),
      `${framework}: Tabs requires ${property} property mapping`,
    );
  }
  assert(
    findEvent(record, "vf-value-change"),
    `${framework}: Tabs requires vf-value-change mapping`,
  );
  assert(
    record.slots.some((slot) => slot.canonical === "default"),
    `${framework}: Tabs requires default content mapping`,
  );
  for (const requirement of REQUIRED_ACCESSIBILITY) {
    assert(
      record.accessibility.includes(requirement),
      `${framework}: Tabs must retain ${requirement}`,
    );
  }
}

export function createFrameworkTabsSliceModel(generationModel) {
  const surfaces = {};
  for (const framework of ["native", "react", "angular", "vue"]) {
    const surface = generationModel.surfaces?.[framework];
    assert(surface, `tabs: missing ${framework} surface`);
    const record = surface.components.find(
      (component) => component.id === FRAMEWORK_TABS_COMPONENT_ID,
    );
    assertRecord(record, framework);
    surfaces[framework] = record;
  }

  assert(
    surfaces.react.adapter.model?.enabled === true &&
      surfaces.react.adapter.model.canonicalProperty === "value" &&
      surfaces.react.adapter.model.publicProperty === "value" &&
      surfaces.react.adapter.model.publicEvent === "onValueChange",
    "react: Tabs controlled value mapping is incomplete",
  );
  assert(
    surfaces.angular.model?.mode === "two-way" &&
      surfaces.angular.model.property === "value" &&
      surfaces.angular.model.event === "valueChange",
    "angular: Tabs two-way value mapping is incomplete",
  );
  assert(
    surfaces.vue.adapter.vModel?.enabled === true &&
      surfaces.vue.adapter.vModel.canonicalProperty === "value" &&
      surfaces.vue.adapter.vModel.publicProperty === "modelValue" &&
      surfaces.vue.adapter.vModel.publicEvent === "update:modelValue",
    "vue: Tabs v-model mapping is incomplete",
  );

  return Object.freeze({
    schemaVersion: 1,
    task: TASK_ID,
    component: FRAMEWORK_TABS_COMPONENT_ID,
    canonicalRenderer: CANONICAL_RENDERER,
    surfaces,
  });
}

function nativeSource() {
  return `${GENERATED_HEADER}
import type {
  VyrnForgeElementForTagName,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type GeneratedVfTabsElement = VyrnForgeElementForTagName<"vf-tabs">;

export interface GeneratedVfTabsOptions {
  value?: string;
  activationMode?: GeneratedVfTabsElement["activationMode"];
  items?: GeneratedVfTabsElement["items"];
  orientation?: GeneratedVfTabsElement["orientation"];
  disabledValues?: GeneratedVfTabsElement["disabledValues"];
  size?: GeneratedVfTabsElement["size"];
  variant?: GeneratedVfTabsElement["variant"];
  onValueChange?: (value: string) => void;
}

export function bindGeneratedVfTabs(
  element: GeneratedVfTabsElement,
  options: GeneratedVfTabsOptions = {},
): () => void {
  if (options.value !== undefined) element.value = options.value;
  if (options.activationMode !== undefined) element.activationMode = options.activationMode;
  if (options.items !== undefined) element.items = options.items;
  if (options.orientation !== undefined) element.orientation = options.orientation;
  if (options.disabledValues !== undefined) element.disabledValues = options.disabledValues;
  if (options.size !== undefined) element.size = options.size;
  if (options.variant !== undefined) element.variant = options.variant;
  element.dataset["vfGeneratedTabs"] = "native";

  const handleValueChange = (event: Event) => {
    options.onValueChange?.(
      (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
    );
  };
  element.addEventListener("vf-value-change", handleValueChange);
  return () => element.removeEventListener("vf-value-change", handleValueChange);
}
`;
}

function reactSource() {
  return `${GENERATED_HEADER}
import {
  forwardRef,
  useEffect,
  useImperativeHandle,
  useLayoutEffect,
  useRef,
} from "react";
import type { ReactNode } from "react";
import type {
  VyrnForgeElementForTagName,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type GeneratedTabsRef = VyrnForgeElementForTagName<"vf-tabs">;

export interface GeneratedTabsProps {
  id?: string;
  "aria-label"?: string;
  value?: string;
  defaultValue?: string;
  activationMode?: GeneratedTabsRef["activationMode"];
  items?: GeneratedTabsRef["items"];
  orientation?: GeneratedTabsRef["orientation"];
  disabledValues?: GeneratedTabsRef["disabledValues"];
  size?: GeneratedTabsRef["size"];
  variant?: GeneratedTabsRef["variant"];
  children?: ReactNode;
  onValueChange?: (value: string) => void;
}

export const GeneratedTabs = forwardRef<GeneratedTabsRef, GeneratedTabsProps>(
  function GeneratedTabs(
    {
      id,
      "aria-label": ariaLabel,
      value,
      defaultValue,
      activationMode,
      items,
      orientation,
      disabledValues,
      size,
      variant,
      children,
      onValueChange,
    },
    forwardedRef,
  ) {
    const elementRef = useRef<GeneratedTabsRef>(null);
    const defaultAppliedRef = useRef(false);

    useImperativeHandle(
      forwardedRef,
      () => elementRef.current as GeneratedTabsRef,
      [],
    );

    useLayoutEffect(() => {
      const element = elementRef.current;
      if (!element) return;
      if (value !== undefined && element.value !== value) element.value = value;
      if (
        value === undefined &&
        !defaultAppliedRef.current &&
        defaultValue !== undefined
      ) {
        element.value = defaultValue;
        defaultAppliedRef.current = true;
      }
      if (activationMode !== undefined) element.activationMode = activationMode;
      if (items !== undefined) element.items = items;
      if (orientation !== undefined) element.orientation = orientation;
      if (disabledValues !== undefined) element.disabledValues = disabledValues;
      if (size !== undefined) element.size = size;
      if (variant !== undefined) element.variant = variant;
    }, [
      value,
      defaultValue,
      activationMode,
      items,
      orientation,
      disabledValues,
      size,
      variant,
    ]);

    useEffect(() => {
      const element = elementRef.current;
      if (!element) return;
      const handleValueChange = (event: Event) => {
        onValueChange?.(
          (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
        );
      };
      element.addEventListener("vf-value-change", handleValueChange);
      return () => element.removeEventListener("vf-value-change", handleValueChange);
    }, [onValueChange]);

    return (
      <vf-tabs
        ref={elementRef}
        id={id}
        aria-label={ariaLabel}
        data-vf-generated-tabs="react"
      >
        {children}
      </vf-tabs>
    );
  },
);

GeneratedTabs.displayName = "GeneratedTabs";
`;
}

function angularSource() {
  return `${GENERATED_HEADER}
import {
  Directive,
  ElementRef,
  EventEmitter,
  Input,
  OnDestroy,
  Output,
} from "@angular/core";
import type {
  VyrnForgeElementForTagName,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type VfTabsElement = VyrnForgeElementForTagName<"vf-tabs">;

@Directive({
  selector: "vf-tabs[vfGeneratedTabs]",
  standalone: true,
  exportAs: "vfTabs",
})
export class VfTabs implements OnDestroy {
  @Output("valueChange")
  readonly valueChange = new EventEmitter<string>();

  private defaultApplied = false;
  private readonly handleValueChange = (event: Event) => {
    this.valueChange.emit(
      (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
    );
  };

  constructor(private readonly element: ElementRef<VfTabsElement>) {
    this.element.nativeElement.dataset["vfGeneratedTabs"] = "angular";
    this.element.nativeElement.addEventListener(
      "vf-value-change",
      this.handleValueChange,
    );
  }

  @Input("value")
  set valueInput(value: string | undefined) {
    if (value !== undefined && this.element.nativeElement.value !== value) {
      this.element.nativeElement.value = value;
    }
  }

  @Input("defaultValue")
  set defaultValueInput(value: string | undefined) {
    if (value !== undefined && !this.defaultApplied) {
      this.element.nativeElement.value = value;
      this.defaultApplied = true;
    }
  }

  @Input("activationMode")
  set activationModeInput(value: VfTabsElement["activationMode"] | undefined) {
    if (value !== undefined) this.element.nativeElement.activationMode = value;
  }

  @Input("items")
  set itemsInput(value: VfTabsElement["items"] | undefined) {
    if (value !== undefined) this.element.nativeElement.items = value;
  }

  @Input("orientation")
  set orientationInput(value: VfTabsElement["orientation"] | undefined) {
    if (value !== undefined) this.element.nativeElement.orientation = value;
  }

  @Input("disabledValues")
  set disabledValuesInput(value: VfTabsElement["disabledValues"] | undefined) {
    if (value !== undefined) this.element.nativeElement.disabledValues = value;
  }

  @Input("size")
  set sizeInput(value: VfTabsElement["size"] | undefined) {
    if (value !== undefined) this.element.nativeElement.size = value;
  }

  @Input("variant")
  set variantInput(value: VfTabsElement["variant"] | undefined) {
    if (value !== undefined) this.element.nativeElement.variant = value;
  }

  ngOnDestroy(): void {
    this.element.nativeElement.removeEventListener(
      "vf-value-change",
      this.handleValueChange,
    );
  }
}
`;
}

function vueSource() {
  return `${GENERATED_HEADER}
import {
  defineComponent,
  h,
  onBeforeUnmount,
  onMounted,
  ref,
  watchEffect,
} from "vue";
import type { PropType } from "vue";
import type {
  VyrnForgeElementForTagName,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type VfTabsElement = VyrnForgeElementForTagName<"vf-tabs">;

export const VfTabs = defineComponent({
  name: "VfTabs",
  inheritAttrs: false,
  props: {
    id: { type: String, default: undefined },
    modelValue: { type: String as PropType<string | undefined>, default: undefined },
    defaultValue: { type: String, default: undefined },
    activationMode: { type: String as PropType<VfTabsElement["activationMode"]>, default: undefined },
    items: { type: Array as PropType<VfTabsElement["items"]>, default: undefined },
    orientation: { type: String as PropType<VfTabsElement["orientation"]>, default: undefined },
    disabledValues: { type: Array as PropType<VfTabsElement["disabledValues"]>, default: undefined },
    size: { type: String as PropType<VfTabsElement["size"]>, default: undefined },
    variant: { type: String as PropType<VfTabsElement["variant"]>, default: undefined },
  },
  emits: {
    "update:modelValue": (_value: string) => true,
    "vf-value-change": (_event: Event) => true,
  },
  setup(props, { attrs, emit, expose, slots }) {
    const elementRef = ref<VfTabsElement | null>(null);
    let defaultApplied = false;

    watchEffect(() => {
      const element = elementRef.value;
      if (!element) return;
      if (props.modelValue !== undefined && element.value !== props.modelValue) {
        element.value = props.modelValue;
      } else if (
        props.modelValue === undefined &&
        !defaultApplied &&
        props.defaultValue !== undefined
      ) {
        element.value = props.defaultValue;
        defaultApplied = true;
      }
      if (props.activationMode !== undefined) element.activationMode = props.activationMode;
      if (props.items !== undefined) element.items = props.items;
      if (props.orientation !== undefined) element.orientation = props.orientation;
      if (props.disabledValues !== undefined) element.disabledValues = props.disabledValues;
      if (props.size !== undefined) element.size = props.size;
      if (props.variant !== undefined) element.variant = props.variant;
    });

    const handleValueChange = (event: Event) => {
      const value = (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value;
      emit("update:modelValue", value);
      emit("vf-value-change", event);
    };

    onMounted(() => {
      elementRef.value?.addEventListener("vf-value-change", handleValueChange);
    });
    onBeforeUnmount(() => {
      elementRef.value?.removeEventListener("vf-value-change", handleValueChange);
    });

    expose({ element: elementRef });

    return () =>
      h(
        "vf-tabs",
        {
          ...attrs,
          id: props.id,
          ref: elementRef,
          "data-vf-generated-tabs": "vue",
        },
        slots.default?.(),
      );
  },
});

export default VfTabs;
`;
}

