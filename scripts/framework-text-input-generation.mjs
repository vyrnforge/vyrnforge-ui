export const FRAMEWORK_TEXT_INPUT_COMPONENT_ID = "text-input";

export const FRAMEWORK_TEXT_INPUT_ARTIFACT_PATHS = Object.freeze({
  native: "tests/consumers/native-html/src/generated/vf-text-input.generated.ts",
  react: "tests/consumers/react/src/generated/TextInput.generated.tsx",
  angular: "tests/consumers/angular/src/app/generated/vf-text-input.generated.ts",
  vue: "tests/consumers/vue/src/generated/VfTextInput.generated.ts",
});

const TASK_ID = "MFD-1113";
const CANONICAL_RENDERER = "@vyrnforge/ui-elements";
const REQUIRED_PROPERTIES = Object.freeze([
  "name",
  "value",
  "disabled",
  "required",
  "label",
]);
const REQUIRED_METHODS = Object.freeze([
  "focus",
  "select",
  "checkValidity",
  "reportValidity",
  "setCustomValidity",
]);

const GENERATED_HEADER = `/**
 * @generated by scripts/generate-framework-text-input-slice.mjs
 * Source: docs/metadata/component-contracts.json (component:text-input)
 * DO NOT EDIT. Regenerate with: npm run generate:framework-artifacts
 */`;

export class FrameworkTextInputGenerationError extends Error {
  constructor(message) {
    super(message);
    this.name = "FrameworkTextInputGenerationError";
  }
}

function assert(condition, message) {
  if (!condition) throw new FrameworkTextInputGenerationError(message);
}

function findProperty(record, canonical) {
  return record.properties.find((property) => property.canonical === canonical);
}

function findEvent(record, canonical) {
  return record.events.find((event) => event.canonical === canonical);
}

function assertRecord(record, framework) {
  assert(record, `text-input: missing ${framework} generation record`);
  assert(
    record.id === FRAMEWORK_TEXT_INPUT_COMPONENT_ID,
    `${framework}: expected text-input record`,
  );
  assert(
    record.adapter.canonicalRenderer === CANONICAL_RENDERER,
    `${framework}: TextInput must keep ${CANONICAL_RENDERER} as canonical renderer`,
  );
  if (framework === "native") {
    assert(record.tag === "vf-text-input", "native: TextInput must target vf-text-input");
  }
  for (const property of REQUIRED_PROPERTIES) {
    assert(
      findProperty(record, property),
      `${framework}: TextInput requires ${property} property mapping`,
    );
  }
  assert(
    findEvent(record, "vf-value-change"),
    `${framework}: TextInput requires vf-value-change mapping`,
  );
  for (const method of REQUIRED_METHODS) {
    assert(
      record.methods.some((entry) => entry.name === method),
      `${framework}: TextInput requires ${method} method mapping`,
    );
  }
  assert(
    record.accessibility.includes("native text-control semantics"),
    `${framework}: TextInput must retain native text-control semantics`,
  );
}

export function createFrameworkTextInputSliceModel(generationModel) {
  const surfaces = {};
  for (const framework of ["native", "react", "angular", "vue"]) {
    const surface = generationModel.surfaces?.[framework];
    assert(surface, `text-input: missing ${framework} surface`);
    const record = surface.components.find(
      (component) => component.id === FRAMEWORK_TEXT_INPUT_COMPONENT_ID,
    );
    assertRecord(record, framework);
    surfaces[framework] = record;
  }

  assert(
    surfaces.react.adapter.model?.enabled === true &&
      surfaces.react.adapter.model.canonicalProperty === "value" &&
      surfaces.react.adapter.model.publicProperty === "value" &&
      surfaces.react.adapter.model.publicEvent === "onValueChange",
    "react: TextInput controlled value mapping is incomplete",
  );
  assert(
    surfaces.angular.adapter.forms?.enabled === true &&
      surfaces.angular.adapter.forms.canonicalProperty === "value" &&
      surfaces.angular.adapter.forms.controlValueAccessor?.disabledProperty ===
        "disabled" &&
      surfaces.angular.adapter.forms.validator?.enabled === true &&
      surfaces.angular.adapter.forms.reset?.supported === true,
    "angular: TextInput Forms/CVA/Validator/reset mapping is incomplete",
  );
  assert(
    surfaces.vue.adapter.vModel?.enabled === true &&
      surfaces.vue.adapter.vModel.canonicalProperty === "value" &&
      surfaces.vue.adapter.vModel.publicProperty === "modelValue" &&
      surfaces.vue.adapter.vModel.publicEvent === "update:modelValue",
    "vue: TextInput v-model mapping is incomplete",
  );

  return Object.freeze({
    schemaVersion: 1,
    task: TASK_ID,
    component: FRAMEWORK_TEXT_INPUT_COMPONENT_ID,
    canonicalRenderer: CANONICAL_RENDERER,
    surfaces,
  });
}

function nativeSource() {
  return `${GENERATED_HEADER}
import type {
  VyrnForgeElementForTagName,
  VyrnForgeInvalidDetail,
  VyrnForgeResetDetail,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type GeneratedVfTextInputElement = VyrnForgeElementForTagName<"vf-text-input">;

export interface GeneratedVfTextInputOptions {
  name?: string;
  value?: string;
  disabled?: boolean;
  required?: boolean;
  label?: string;
  onValueChange?: (value: string) => void;
  onInvalid?: (detail: VyrnForgeInvalidDetail) => void;
  onReset?: (detail: VyrnForgeResetDetail) => void;
}

export function bindGeneratedVfTextInput(
  element: GeneratedVfTextInputElement,
  options: GeneratedVfTextInputOptions = {},
): () => void {
  if (options.name !== undefined) element.name = options.name;
  if (options.value !== undefined) element.value = options.value;
  if (options.disabled !== undefined) element.disabled = options.disabled;
  if (options.required !== undefined) element.required = options.required;
  if (options.label !== undefined) element.label = options.label;
  element.dataset["vfGeneratedTextInput"] = "native";

  const handleValueChange = (event: Event) => {
    options.onValueChange?.(
      (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
    );
  };
  const handleInvalid = (event: Event) => {
    options.onInvalid?.((event as CustomEvent<VyrnForgeInvalidDetail>).detail);
  };
  const handleReset = (event: Event) => {
    options.onReset?.((event as CustomEvent<VyrnForgeResetDetail>).detail);
  };

  element.addEventListener("vf-value-change", handleValueChange);
  element.addEventListener("vf-invalid", handleInvalid);
  element.addEventListener("vf-reset", handleReset);
  return () => {
    element.removeEventListener("vf-value-change", handleValueChange);
    element.removeEventListener("vf-invalid", handleInvalid);
    element.removeEventListener("vf-reset", handleReset);
  };
}
`;
}

function reactSource() {
  return `${GENERATED_HEADER}
import {
  forwardRef,
  useEffect,
  useImperativeHandle,
  useLayoutEffect,
  useRef,
} from "react";
import type {
  VyrnForgeElementForTagName,
  VyrnForgeInvalidDetail,
  VyrnForgeResetDetail,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type GeneratedTextInputRef = VyrnForgeElementForTagName<"vf-text-input">;

export interface GeneratedTextInputProps {
  id?: string;
  name?: string;
  value?: string;
  disabled?: boolean;
  required?: boolean;
  label?: string;
  onValueChange?: (value: string) => void;
  onInvalid?: (detail: VyrnForgeInvalidDetail) => void;
  onReset?: (detail: VyrnForgeResetDetail) => void;
}

export const GeneratedTextInput = forwardRef<
  GeneratedTextInputRef,
  GeneratedTextInputProps
>(function GeneratedTextInput(
  { id, name, value, disabled, required, label, onValueChange, onInvalid, onReset },
  forwardedRef,
) {
  const elementRef = useRef<GeneratedTextInputRef>(null);

  useImperativeHandle(
    forwardedRef,
    () => elementRef.current as GeneratedTextInputRef,
    [],
  );

  useLayoutEffect(() => {
    const element = elementRef.current;
    if (!element) return;
    if (name !== undefined) element.name = name;
    if (value !== undefined && element.value !== value) element.value = value;
    if (disabled !== undefined) element.disabled = disabled;
    if (required !== undefined) element.required = required;
    if (label !== undefined) element.label = label;
  }, [name, value, disabled, required, label]);

  useEffect(() => {
    const element = elementRef.current;
    if (!element) return;
    const handleValueChange = (event: Event) => {
      onValueChange?.(
        (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
      );
    };
    const handleInvalid = (event: Event) => {
      onInvalid?.((event as CustomEvent<VyrnForgeInvalidDetail>).detail);
    };
    const handleReset = (event: Event) => {
      onReset?.((event as CustomEvent<VyrnForgeResetDetail>).detail);
    };
    element.addEventListener("vf-value-change", handleValueChange);
    element.addEventListener("vf-invalid", handleInvalid);
    element.addEventListener("vf-reset", handleReset);
    return () => {
      element.removeEventListener("vf-value-change", handleValueChange);
      element.removeEventListener("vf-invalid", handleInvalid);
      element.removeEventListener("vf-reset", handleReset);
    };
  }, [onValueChange, onInvalid, onReset]);

  return (
    <vf-text-input
      ref={elementRef}
      id={id}
      data-vf-generated-text-input="react"
    />
  );
});

GeneratedTextInput.displayName = "GeneratedTextInput";
`;
}

function angularSource() {
  return `${GENERATED_HEADER}
import {
  Directive,
  ElementRef,
  EventEmitter,
  Input,
  OnDestroy,
  Output,
} from "@angular/core";
import type {
  VyrnForgeElementForTagName,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type VfTextInputElement = VyrnForgeElementForTagName<"vf-text-input">;

@Directive({
  selector: "vf-text-input[vfGeneratedTextInput]",
  standalone: true,
  exportAs: "vfTextInput",
})
export class VfTextInput implements OnDestroy {
  @Output("valueChange")
  readonly valueChange = new EventEmitter<string>();

  private readonly handleValueChange = (event: Event) => {
    this.valueChange.emit(
      (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
    );
  };

  constructor(private readonly element: ElementRef<VfTextInputElement>) {
    this.element.nativeElement.dataset["vfGeneratedTextInput"] = "angular";
    this.element.nativeElement.addEventListener(
      "vf-value-change",
      this.handleValueChange,
    );
  }

  @Input("name")
  set nameInput(value: string | undefined) {
    if (value !== undefined) this.element.nativeElement.name = value;
  }

  @Input("value")
  set valueInput(value: string | undefined) {
    if (value !== undefined && this.element.nativeElement.value !== value) {
      this.element.nativeElement.value = value;
    }
  }

  @Input("disabled")
  set disabledInput(value: boolean | undefined) {
    if (value !== undefined) this.element.nativeElement.disabled = value;
  }

  @Input("required")
  set requiredInput(value: boolean | undefined) {
    if (value !== undefined) this.element.nativeElement.required = value;
  }

  @Input("label")
  set labelInput(value: string | undefined) {
    if (value !== undefined) this.element.nativeElement.label = value;
  }

  focus(): void {
    this.element.nativeElement.focus();
  }

  select(): void {
    this.element.nativeElement.select();
  }

  checkValidity(): boolean {
    return this.element.nativeElement.checkValidity();
  }

  reportValidity(): boolean {
    return this.element.nativeElement.reportValidity();
  }

  setCustomValidity(message: string): void {
    this.element.nativeElement.setCustomValidity(message);
  }

  ngOnDestroy(): void {
    this.element.nativeElement.removeEventListener(
      "vf-value-change",
      this.handleValueChange,
    );
  }
}
`;
}

function vueSource() {
  return `${GENERATED_HEADER}
import {
  defineComponent,
  h,
  onBeforeUnmount,
  onMounted,
  ref,
  watchEffect,
} from "vue";
import type { PropType } from "vue";
import type {
  VyrnForgeElementForTagName,
  VyrnForgeValueChangeDetail,
} from "@vyrnforge/ui-elements";

export type VfTextInputElement = VyrnForgeElementForTagName<"vf-text-input">;

export const VfTextInput = defineComponent({
  name: "VfTextInput",
  inheritAttrs: false,
  props: {
    id: { type: String, default: undefined },
    name: { type: String, default: undefined },
    modelValue: { type: String as PropType<string>, default: "" },
    disabled: { type: Boolean, default: false },
    required: { type: Boolean, default: false },
    label: { type: String, default: undefined },
  },
  emits: {
    "update:modelValue": (_value: string) => true,
    "vf-value-change": (_event: Event) => true,
  },
  setup(props, { attrs, emit, expose }) {
    const elementRef = ref<VfTextInputElement | null>(null);

    watchEffect(() => {
      const element = elementRef.value;
      if (!element) return;
      if (props.name !== undefined) element.name = props.name;
      if (element.value !== props.modelValue) element.value = props.modelValue;
      element.disabled = props.disabled;
      element.required = props.required;
      if (props.label !== undefined) element.label = props.label;
    });

    const handleValueChange = (event: Event) => {
      emit(
        "update:modelValue",
        (event as CustomEvent<VyrnForgeValueChangeDetail<string>>).detail.value,
      );
      emit("vf-value-change", event);
    };

    onMounted(() => {
      elementRef.value?.addEventListener("vf-value-change", handleValueChange);
    });
    onBeforeUnmount(() => {
      elementRef.value?.removeEventListener("vf-value-change", handleValueChange);
    });

    expose({
      element: elementRef,
      focus: () => elementRef.value?.focus(),
      select: () => elementRef.value?.select(),
      checkValidity: () => elementRef.value?.checkValidity() ?? true,
      reportValidity: () => elementRef.value?.reportValidity() ?? true,
      setCustomValidity: (message: string) =>
        elementRef.value?.setCustomValidity(message),
    });

    return () =>
      h("vf-text-input", {
        ...attrs,
        id: props.id,
        ref: elementRef,
        "data-vf-generated-text-input": "vue",
      });
  },
});

export default VfTextInput;
`;
}

