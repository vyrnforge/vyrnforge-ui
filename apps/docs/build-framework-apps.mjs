import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';
import { publicPackageAliases } from './example-compiler.mjs';

const sources = Object.freeze({
  react: `
    import { createElement } from 'react';
    import { createRoot } from 'react-dom/client';
    import { flushSync } from 'react-dom';
    import { AppShell, AppShellHeader, AppShellBody, AppShellNavigation, AppShellMain, AppShellFooter } from '@vyrnforge/react/app-shell';
    import { Input } from '@vyrnforge/react/input';
    import { SideNav, SideNavGroup, SideNavGroupLabel, SideNavList, SideNavItem, SideNavLink } from '@vyrnforge/react/side-nav';

    const model = JSON.parse(document.querySelector('#vf-docs-page-model').textContent || '{}');
    const reactAttributeNames = Object.freeze({
      class: 'className',
      for: 'htmlFor',
      autocomplete: 'autoComplete',
      spellcheck: 'spellCheck',
      tabindex: 'tabIndex',
      readonly: 'readOnly',
      maxlength: 'maxLength',
      minlength: 'minLength'
    });
    const booleanAttributes = new Set(['checked', 'disabled', 'hidden', 'multiple', 'open', 'readonly', 'required', 'selected']);

    function propsFor(element) {
      const props = {};
      for (const attribute of element.attributes) {
        const name = reactAttributeNames[attribute.name] || attribute.name;
        props[name] = booleanAttributes.has(attribute.name) ? true : attribute.value;
      }
      return props;
    }

    function componentFor(element) {
      if (element.hasAttribute('data-vf-side-nav')) return SideNav;
      if (element.hasAttribute('data-vf-side-nav-group')) return SideNavGroup;
      if (element.hasAttribute('data-vf-side-nav-group-label')) return SideNavGroupLabel;
      if (element.hasAttribute('data-vf-side-nav-list')) return SideNavList;
      if (element.hasAttribute('data-vf-side-nav-item')) return SideNavItem;
      if (element.hasAttribute('data-vf-side-nav-link')) return SideNavLink;
      if (element.matches('input[data-vf-docs-search], input[data-vf-input]')) return Input;
      return element.localName;
    }

    function renderNode(node, key) {
      if (node.nodeType === Node.TEXT_NODE) return node.textContent;
      if (node.nodeType !== Node.ELEMENT_NODE) return null;
      const element = node;
      const Component = componentFor(element);
      const props = propsFor(element);
      if (Component === SideNavLink) props.current = element.getAttribute('data-vf-current') === 'true';
      props.key = key;
      const children = Array.from(element.childNodes).map((child, index) => renderNode(child, index));
      return createElement(Component, props, ...children);
    }

    function renderFragment(value) {
      // The fragment is generated by the docs build, not supplied by users. It is parsed only
      // as an intermediate semantic tree; React owns the live DOM and VyrnForge surfaces below.
      const template = document.createElement('template');
      template.innerHTML = value || '';
      return Array.from(template.content.childNodes).map((node, index) => renderNode(node, index));
    }

    const root = createRoot(document.querySelector('#vf-docs-app'));
    flushSync(() => root.render(
      createElement(AppShell, { 'data-vf-docs-renderer': 'react' },
        createElement('a', { className: 'vf-skip-link', href: '#main' }, 'Skip to content'),
        createElement(AppShellHeader, { className: 'vf-docs-header' }, ...renderFragment(model.headerHtml)),
        createElement(AppShellBody, null,
          createElement(AppShellNavigation, { className: 'vf-docs-navigation' }, ...renderFragment(model.navigationHtml)),
          createElement(AppShellMain, { id: 'main' }, ...renderFragment(model.mainHtml))
        ),
        createElement(AppShellFooter, { className: 'vf-docs-footer' }, model.footerText || '')
      )
    ));
    document.documentElement.dataset.vfDocsRendered = 'react';
    document.dispatchEvent(new CustomEvent('vfdocsrendered', { detail: { framework: 'react' } }));
  `,
  angular: `
    import '@angular/compiler';
    import { Component, provideZonelessChangeDetection } from '@angular/core';
    import { bootstrapApplication } from '@angular/platform-browser';
    import {
      VfAppShellDirective,
      VfAppShellHeaderDirective,
      VfAppShellBodyDirective,
      VfAppShellNavigationDirective,
      VfAppShellMainDirective,
      VfAppShellFooterDirective
    } from '@vyrnforge/angular/app-shell';
    import { VfInputDirective } from '@vyrnforge/angular/input';
    import {
      VfSideNavDirective,
      VfSideNavGroupDirective,
      VfSideNavGroupLabelDirective,
      VfSideNavListDirective,
      VfSideNavItemDirective,
      VfSideNavLinkDirective
    } from '@vyrnforge/angular/side-nav';

    const model = JSON.parse(document.querySelector('#vf-docs-page-model').textContent || '{}');

    function angularFragment(value) {
      // Convert generated framework-neutral VyrnForge hooks to the Angular public directives.
      return (value || '')
        .replaceAll('data-vf-side-nav-group-label', 'vfSideNavGroupLabel')
        .replaceAll('data-vf-side-nav-group', 'vfSideNavGroup')
        .replaceAll('data-vf-side-nav-list', 'vfSideNavList')
        .replaceAll('data-vf-side-nav-item', 'vfSideNavItem')
        .replaceAll('data-vf-side-nav-link', 'vfSideNavLink')
        .replaceAll('data-vf-side-nav', 'vfSideNav')
        .replaceAll('data-vf-current="true"', '[vfSideNavCurrent]="true"')
        .replace(/<input([^>]*data-vf-docs-search[^>]*)>/g, '<input vfInput$1>')
        .replace(/<input([^>]*data-vf-input[^>]*)>/g, '<input vfInput$1>');
    }

    const template = \`
      <div vfAppShell data-vf-docs-renderer="angular">
        <a class="vf-skip-link" href="#main">Skip to content</a>
        <header vfAppShellHeader class="vf-docs-header">\${angularFragment(model.headerHtml)}</header>
        <div vfAppShellBody>
          <aside vfAppShellNavigation class="vf-docs-navigation">\${angularFragment(model.navigationHtml)}</aside>
          <main vfAppShellMain id="main">\${angularFragment(model.mainHtml)}</main>
        </div>
        <footer vfAppShellFooter class="vf-docs-footer">\${model.footerText || ''}</footer>
      </div>
    \`;

    @Component({
      selector: 'vf-docs-angular-root',
      standalone: true,
      imports: [
        VfAppShellDirective,
        VfAppShellHeaderDirective,
        VfAppShellBodyDirective,
        VfAppShellNavigationDirective,
        VfAppShellMainDirective,
        VfAppShellFooterDirective,
        VfInputDirective,
        VfSideNavDirective,
        VfSideNavGroupDirective,
        VfSideNavGroupLabelDirective,
        VfSideNavListDirective,
        VfSideNavItemDirective,
        VfSideNavLinkDirective
      ],
      template
    })
    class DocsApp {}

    bootstrapApplication(DocsApp, { providers: [provideZonelessChangeDetection()] }).then(() => {
      document.documentElement.dataset.vfDocsRendered = 'angular';
      document.dispatchEvent(new CustomEvent('vfdocsrendered', { detail: { framework: 'angular' } }));
    });
  `,
  vue: `
    import { createApp, h } from 'vue';
    import { AppShell, AppShellHeader, AppShellBody, AppShellNavigation, AppShellMain, AppShellFooter } from '@vyrnforge/vue/app-shell';
    import { Input } from '@vyrnforge/vue/input';
    import { SideNav, SideNavGroup, SideNavGroupLabel, SideNavList, SideNavItem, SideNavLink } from '@vyrnforge/vue/side-nav';

    const model = JSON.parse(document.querySelector('#vf-docs-page-model').textContent || '{}');

    function propsFor(element) {
      const props = {};
      for (const attribute of element.attributes) props[attribute.name] = attribute.value || '';
      if (element.hasAttribute('hidden')) props.hidden = true;
      if (element.hasAttribute('open')) props.open = true;
      return props;
    }

    function componentFor(element) {
      if (element.hasAttribute('data-vf-side-nav')) return SideNav;
      if (element.hasAttribute('data-vf-side-nav-group')) return SideNavGroup;
      if (element.hasAttribute('data-vf-side-nav-group-label')) return SideNavGroupLabel;
      if (element.hasAttribute('data-vf-side-nav-list')) return SideNavList;
      if (element.hasAttribute('data-vf-side-nav-item')) return SideNavItem;
      if (element.hasAttribute('data-vf-side-nav-link')) return SideNavLink;
      if (element.matches('input[data-vf-docs-search], input[data-vf-input]')) return Input;
      return element.localName;
    }

    function renderNode(node) {
      if (node.nodeType === Node.TEXT_NODE) return node.textContent;
      if (node.nodeType !== Node.ELEMENT_NODE) return null;
      const element = node;
      const Component = componentFor(element);
      const props = propsFor(element);
      if (Component === SideNavLink) props.current = element.getAttribute('data-vf-current') === 'true';
      const children = Array.from(element.childNodes).map(renderNode);
      return h(Component, props, children);
    }

    function renderFragment(value) {
      // The generated fragment is only an intermediate tree. Vue creates and owns the live VNodes.
      const template = document.createElement('template');
      template.innerHTML = value || '';
      return Array.from(template.content.childNodes).map(renderNode);
    }

    const app = createApp({
      render() {
        return h(AppShell, { 'data-vf-docs-renderer': 'vue' }, {
          default: () => [
            h('a', { class: 'vf-skip-link', href: '#main' }, 'Skip to content'),
            h(AppShellHeader, { class: 'vf-docs-header' }, { default: () => renderFragment(model.headerHtml) }),
            h(AppShellBody, null, {
              default: () => [
                h(AppShellNavigation, { class: 'vf-docs-navigation' }, { default: () => renderFragment(model.navigationHtml) }),
                h(AppShellMain, { id: 'main' }, { default: () => renderFragment(model.mainHtml) })
              ]
            }),
            h(AppShellFooter, { class: 'vf-docs-footer' }, { default: () => model.footerText || '' })
          ]
        });
      }
    });
    app.mount('#vf-docs-app');
    document.documentElement.dataset.vfDocsRendered = 'vue';
    document.dispatchEvent(new CustomEvent('vfdocsrendered', { detail: { framework: 'vue' } }));
  `
});

export async function buildFrameworkDocsApps({ root, channelRoot }) {
  const outputRoot = path.join(channelRoot, 'assets/framework-apps');
  await mkdir(outputRoot, { recursive: true });
  const aliases = publicPackageAliases(root);

  for (const [framework, contents] of Object.entries(sources)) {
    await build({
      stdin: {
        resolveDir: root,
        sourcefile: `vyrnforge-docs-${framework}.ts`,
        loader: framework === 'react' ? 'tsx' : 'ts',
        contents
      },
      alias: aliases,
      bundle: true,
      format: 'iife',
      platform: 'browser',
      target: ['es2022'],
      legalComments: 'none',
      tsconfigRaw: {
        compilerOptions: framework === 'angular'
          ? { experimentalDecorators: true, useDefineForClassFields: false }
          : framework === 'react'
            ? { jsx: 'react' }
            : {}
      },
      outfile: path.join(outputRoot, `${framework}.js`)
    });
  }
}
